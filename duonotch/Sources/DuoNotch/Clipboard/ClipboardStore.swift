import AppKit
import Combine

struct ClipItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let copiedAt: Date
}

/// A saved piece of text you paste often.
struct Snippet: Identifiable, Codable, Equatable {
    var id: UUID = UUID()
    var title: String
    var text: String

    var displayTitle: String {
        let t = title.trimmingCharacters(in: .whitespacesAndNewlines)
        return t.isEmpty ? ClipboardStore.oneLine(text) : t
    }
}

/// Recent clipboard text (kept in memory only) and pinned snippets
/// (saved in preferences). Copies that password managers mark as
/// concealed or transient are never recorded.
@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    @Published var enabled: Bool {
        didSet {
            UserDefaults.standard.set(enabled, forKey: Keys.enabled)
            if !enabled { history = [] }
            restartTimer()
        }
    }
    @Published var historyLimit: Int {
        didSet { UserDefaults.standard.set(historyLimit, forKey: Keys.limit); trim() }
    }
    @Published private(set) var history: [ClipItem] = []
    @Published var snippets: [Snippet] {
        didSet { persistSnippets() }
    }
    /// Briefly set after a click so the row can say "Copied".
    @Published private(set) var lastCopiedText: String?

    private enum Keys {
        static let enabled = "clipboard.enabled"
        static let limit = "clipboard.historyLimit"
        static let snippets = "clipboard.snippets.v1"
    }

    /// Pasteboard types that mean "don't keep this" (nspasteboard.org convention,
    /// used by 1Password, Bitwarden, Keychain Access and others).
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var clearCopiedTask: Task<Void, Never>?

    private init() {
        let d = UserDefaults.standard
        enabled = d.object(forKey: Keys.enabled) as? Bool ?? true
        let limit = d.integer(forKey: Keys.limit)
        historyLimit = limit > 0 ? limit : 20
        if let data = d.data(forKey: Keys.snippets),
           let decoded = try? JSONDecoder().decode([Snippet].self, from: data) {
            snippets = decoded
        } else {
            snippets = []
        }
        restartTimer()
    }

    // MARK: - Actions

    func copy(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChangeCount = pb.changeCount
        // Move it to the top of the history instead of duplicating it.
        if enabled {
            history.removeAll { $0.text == text }
            history.insert(ClipItem(text: text, copiedAt: Date()), at: 0)
            trim()
        }
        lastCopiedText = text
        clearCopiedTask?.cancel()
        clearCopiedTask = Task { [weak self] in
            try? await Task.sleep(for: .seconds(1.2))
            guard !Task.isCancelled else { return }
            self?.lastCopiedText = nil
        }
    }

    func pin(_ item: ClipItem) {
        guard !snippets.contains(where: { $0.text == item.text }) else { return }
        snippets.insert(Snippet(title: "", text: item.text), at: 0)
    }

    func saveCurrentClipboard() {
        guard let text = NSPasteboard.general.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              !snippets.contains(where: { $0.text == text }) else { return }
        snippets.insert(Snippet(title: "", text: text), at: 0)
    }

    func removeSnippet(_ snippet: Snippet) {
        snippets.removeAll { $0.id == snippet.id }
    }

    func clearHistory() {
        history = []
    }

    nonisolated static func oneLine(_ text: String) -> String {
        text.trimmingCharacters(in: .whitespacesAndNewlines)
            .components(separatedBy: .newlines)
            .joined(separator: " ⏎ ")
    }

    // MARK: - Polling

    private func restartTimer() {
        timer?.invalidate()
        timer = nil
        guard enabled else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardStore.shared.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes),
              let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= 20_000 else { return }
        history.removeAll { $0.text == text }
        history.insert(ClipItem(text: text, copiedAt: Date()), at: 0)
        trim()
    }

    private func trim() {
        if history.count > historyLimit { history = Array(history.prefix(historyLimit)) }
    }

    private func persistSnippets() {
        if let data = try? JSONEncoder().encode(snippets) {
            UserDefaults.standard.set(data, forKey: Keys.snippets)
        }
    }
}
